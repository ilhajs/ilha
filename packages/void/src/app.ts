import { atom, h } from "ilha";
import type { View } from "ilha";
import type { PageObject } from "void/pages-protocol";

import { VoidContext } from "./context";
import type { VoidPageState } from "./context";
import type { FieldErrors, JsonRecord, PageProps } from "./types";

/** A page or layout component: the default export of a module in `pages/`. */
export type PageComponent = (
  props: never
) =>
  | View
  | Promise<View | undefined>
  | Generator<View, View | undefined, View>
  | undefined;

export interface PageModule {
  readonly default: PageComponent;
}

/** Lazy component imports generated by Void's component manifest. */
export type ComponentManifest = Readonly<
  Record<string, () => Promise<PageModule>>
>;

/** Page component ID → layout IDs, outermost first. */
export type LayoutTree = Record<string, string[]>;

/** Everything one render of a Void page needs. */
export interface PageTree {
  readonly page: PageComponent | null;
  /**
   * Identity of the page instance. A new key mounts the page with fresh
   * state; layouts keep theirs because they stay unkeyed.
   */
  readonly pageKey: string;
  readonly props: PageProps;
  readonly layouts: readonly PageComponent[];
  readonly state: VoidPageState;
}

const composeTree = ({
  layouts,
  page,
  pageKey,
  props,
  state,
}: PageTree): View => {
  if (!page) {
    return null;
  }
  let view: View = h(page, { ...props, key: pageKey });
  for (let index = layouts.length - 1; index >= 0; index -= 1) {
    const layout = layouts[index];
    if (layout) {
      view = h(layout, null, view);
    }
  }
  return h(VoidContext.Provider, { value: state }, view);
};

export interface PageRootOptions {
  /** Return the tree to render. Called on every render of the root. */
  read: () => PageTree;
  /** Receive a function that rerenders the root after the tree changes. */
  connect?: (rerender: () => void) => void;
}

/**
 * Root component for a Void page. The server and the client render the same
 * root, so hydration snapshots line up slot for slot.
 */
export const createPageRoot =
  ({ connect, read }: PageRootOptions) =>
  (): View => {
    const version = atom(0);
    connect?.(() => version.update((current) => current + 1));
    version();
    return composeTree(read());
  };

export interface LoadPageTreeOptions {
  components: ComponentManifest;
  layoutTree: LayoutTree;
  componentId: string;
}

/** Import a page component and its layout chain. */
export const loadPageComponents = async ({
  componentId,
  components,
  layoutTree,
}: LoadPageTreeOptions): Promise<{
  page: PageComponent;
  layouts: PageComponent[];
}> => {
  const load = async (id: string): Promise<PageComponent> => {
    const importer = components[id];
    if (!importer) {
      throw new Error(`@ilha/void: no component registered for "${id}".`);
    }
    const mod = await importer();
    return mod.default;
  };
  const [page, ...layouts] = await Promise.all([
    load(componentId),
    ...(layoutTree[componentId] ?? []).map(load),
  ]);
  // SAFETY: Promise.all resolved at least the page entry.
  return { layouts, page: page as PageComponent };
};

/** The parts of Void page data a render reads. */
export interface RouteData {
  pageId: string;
  props: PageProps;
  params: Readonly<Record<string, string>>;
  shared: JsonRecord;
  errors: FieldErrors;
}

/** Read the render inputs from a Void page object. */
export const routeData = (pageData: PageObject): RouteData => ({
  errors: pageData.errors ?? {},
  pageId: pageData.component,
  params: pageData.params ?? {},
  // SAFETY: Void serializes loader results as JSON; on the client, deferred
  // props arrive as the states `startPages` creates.
  props: pageData.props as PageProps,
  // SAFETY: shared values cross the wire as JSON page data.
  shared: (pageData.shared ?? {}) as JsonRecord,
});
